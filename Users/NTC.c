float NTC_Cov(int ADC_Data) {
	float Temp;
	uint16_t i = 40;
	if (ADC_Data >= 3003) {
		while (ADC_Data >= NTC3380_10k[i]) {
			i--;
		}
		Temp = i + ((float) ADC_Data - NTC3380_10k[i + 1]) / (NTC3380_10k[i] - NTC3380_10k[i + 1]) - 40;
	} else {
		while (ADC_Data <= NTC3380_10k[i]) {
			i++;
		}
		Temp = i + ((float) ADC_Data - NTC3380_10k[i]) / (NTC3380_10k[i - 1] - NTC3380_10k[i]) - 40;
	}
	return Temp;
}
